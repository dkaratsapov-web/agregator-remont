#!/usr/bin/env bash
# Совместимость миграций со старым кодом: bash deploy/autodeploy/migration-check.sh <от> <до>
# Разбор SQL по операторам и белый список безопасных операций — migration_check.py (описание
# там). Опасный оператор допустим только с пометкой прямо перед ним:
#   -- rollback-safe: <почему прежний код с ним работает>
# Код выхода: 0 — совместимо, 2 — есть непомеченные опасные операции (список в выводе).
# Используют rollback.sh (откат на старые образы поверх новой схемы) и CI (новые миграции PR).
# Это ограждение, а не доказательство: исполняемая проверка — scripts/schema-compat-test.sh.
set -euo pipefail

: "${1:?укажите коммит «от»}" "${2:?укажите коммит «до»}"
exec python3 "$(cd "$(dirname "$0")" && pwd)/migration_check.py" "$1" "$2"
