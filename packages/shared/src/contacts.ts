/**
 * Обмен контактами в сделке по согласию сторон. Телефон и email не видны никому, пока их
 * владелец сам не откроет их второй стороне сделки (заказчику или выбранному исполнителю).
 * Согласие привязано к выбранному отклику: после отказа исполнителя или выбора другого
 * его нужно дать заново. Открытые контакты можно снова скрыть.
 */
import type { PlanParty } from './plans';

/** Контакты стороны, которые она открыла. */
export interface PartyContactsDto {
  name: string;
  /** +7XXXXXXXXXX; null — телефон в профиле не указан. */
  phone: string | null;
  email: string;
}

/** Обмен контактами по заказу для стороны сделки. */
export interface ContactExchangeDto {
  /** Кто смотрит: заказчик или исполнитель. */
  viewer: PlanParty;
  /** Имя второй стороны (видно в сделке всегда). */
  counterpartName: string;
  /** Когда я открыл свои контакты второй стороне (ISO 8601); null — не открывал. */
  mySharedAt: string | null;
  /** Телефон в моём профиле указан (иначе вторая сторона увидит только email). */
  myPhoneSet: boolean;
  /** Контакты второй стороны; null — она их не открывала. */
  theirs: PartyContactsDto | null;
}
